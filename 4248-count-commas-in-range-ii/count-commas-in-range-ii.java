class Solution {
    public long countCommas(long n) {
        // long ans=0;
        // for(long i=1000;i<=n;i*=1000){
        //     ans+=n-i+1;
        // }
        // return ans;

        if(n<=999) return 0;
        if(n>=1000 && n<=999999) return (n-1000+1);
        if(n>=1000000 && n<=999999999) return (999999-1000+1)+(2*(n-1000000+1));
        if(n>=1000000000L && n<=999999999999L) return (999999-1000+1)+(2*(999999999-1000000+1))+(3*(n-1000000000L+1));
        if(n>=1000000000000L && n<=999999999999999L) return (999999-1000+1)+(2*(999999999-1000000+1))+(3*(999999999999L-1000000000L+1))+(4*(n-1000000000000L+1));
        return (999999-1000+1)+(2*(999999999-1000000+1))+(3*(999999999999L-1000000000L+1))+(4*(999999999999999L-1000000000000L+1))+(5*(n-1000000000000000L+1));
    }
}